import os
import re
import time
from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Annotated, AsyncIterator, Generic, TypeVar

from fastapi import Depends

from pydantic import BaseModel

from core.settings import Settings, get_settings


T = TypeVar("T", bound=BaseModel)


@dataclass
class LLMResponse:
    text: str
    model: str
    input_tokens: int
    output_tokens: int
    latency_ms: float
    raw: object
    sources: list[str] | None = None


@dataclass
class ParsedResponse(Generic[T]):
    parsed: T | None
    text: str
    model: str
    input_tokens: int
    output_tokens: int
    latency_ms: float
    raw: object
    sources: list[str]


class LLMClient(ABC):
    async def aclose(self) -> None:
        """Release any underlying HTTP connections. No-op by default."""
        return None

    @abstractmethod
    async def _call(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: float,
        max_tokens: int,
        model: str | None = None,
        web_search: bool = False,
    ) -> LLMResponse:
        ...

    @abstractmethod
    async def _parse(
        self,
        system_prompt: str,
        user_prompt: str,
        response_format: type[T],
        temperature: float,
        max_tokens: int,
        model: str | None = None,
        web_search: bool = False,
    ) -> ParsedResponse[T]:
        ...

    @abstractmethod
    def provider_name(self) -> str:
        ...

    async def generate(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: float = 0.3,
        max_tokens: int = 1000,
        model: str | None = None,
        web_search: bool = False,
    ) -> LLMResponse:
        return await self._call(
            system_prompt=system_prompt,
            user_prompt=user_prompt,
            temperature=temperature,
            max_tokens=max_tokens,
            model=model,
            web_search=web_search,
        )

    async def parse(
        self,
        system_prompt: str,
        user_prompt: str,
        response_format: type[T],
        temperature: float = 0.3,
        max_tokens: int = 1000,
        model: str | None = None,
        web_search: bool = False,
    ) -> ParsedResponse[T]:
        return await self._parse(
            system_prompt=system_prompt,
            user_prompt=user_prompt,
            response_format=response_format,
            temperature=temperature,
            max_tokens=max_tokens,
            model=model,
            web_search=web_search,
        )


